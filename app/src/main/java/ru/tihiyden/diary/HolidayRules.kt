package ru.tihiyden.diary

import java.time.DayOfWeek
import java.time.LocalDate
import java.time.temporal.TemporalAdjusters

enum class HolidayKind(val label: String, val pluralLabel: String, val defaultColor: Int, val defaultTint: Int) {
    PUBLIC("Государственный праздник", "Государственные", 0xFFA52440.toInt(), 0xFFFFE6EC.toInt()),
    MEMORIAL("Памятная дата", "Памятные даты", 0xFF2C5DA5.toInt(), 0xFFE5EFFF.toInt()),
    PROFESSIONAL("Профессиональный праздник", "Профессиональные", 0xFF8A530B.toInt(), 0xFFFFEBD3.toInt()),
}
data class Holiday(val id: String, val date: LocalDate, val title: String, val kind: HolidayKind)
data class HolidaySettings(
    val enabled: Boolean = true,
    val public: Boolean = true,
    val memorial: Boolean = true,
    val professional: Boolean = true,
    val dayTypes: Boolean = true,
    val autoUpdate: Boolean = true,
    val colors: Map<HolidayKind, Int> = emptyMap(),
) {
    fun shows(kind: HolidayKind): Boolean = enabled && includes(kind)

    fun includes(kind: HolidayKind): Boolean = when (kind) {
        HolidayKind.PUBLIC -> public
        HolidayKind.MEMORIAL -> memorial
        HolidayKind.PROFESSIONAL -> professional
    }

    fun withCategory(kind: HolidayKind, checked: Boolean): HolidaySettings = when (kind) {
        HolidayKind.PUBLIC -> copy(public = checked)
        HolidayKind.MEMORIAL -> copy(memorial = checked)
        HolidayKind.PROFESSIONAL -> copy(professional = checked)
    }

    fun color(kind: HolidayKind): Int = colors[kind] ?: kind.defaultColor

    fun withColor(kind: HolidayKind, color: Int): HolidaySettings =
        copy(colors = if (color == kind.defaultColor) colors - kind else colors + (kind to color))
}

/** Current federal observances. Date facts and sources are documented in HOLIDAYS_SOURCES.md. */
object HolidayRules {
    const val REVIEWED = "04.11.2026"
    fun holidays(year: Int): List<Holiday> = buildList {
        require(year in 1900..2100)
        fun addHoliday(key: String, date: LocalDate, title: String, kind: HolidayKind) {
            add(Holiday("ru:$key:${date}", date, title, kind))
        }
        // A fallback for years whose production calendar has not been downloaded.
        if (year >= 2013) {
            (1..8).forEach { day -> addHoliday("public-$day", LocalDate.of(year, 1, day), if (day == 7) "Рождество Христово" else "Новогодние каникулы", HolidayKind.PUBLIC) }
            listOf("02.23" to "День защитника Отечества", "03.08" to "Международный женский день", "05.01" to "Праздник Весны и Труда", "05.09" to "День Победы", "06.12" to "День России", "11.04" to "День народного единства").forEach { (day, title) ->
                addHoliday("public-$day", date(year, day), title, HolidayKind.PUBLIC)
            }
        }
        // Do not apply today's commemorative calendar retroactively to historical years.
        if (year < 2026) return@buildList
        fixed.lineSequence().filter { it.isNotBlank() }.forEachIndexed { index, line ->
            val parts = line.split('|')
            val kind = if (parts[1] == "P") HolidayKind.PROFESSIONAL else HolidayKind.MEMORIAL
            addHoliday("fixed-$index", date(year, parts[0]), parts[2], kind)
        }
        moving.lineSequence().filter { it.isNotBlank() }.forEachIndexed { index, line ->
            val parts = line.split('|')
            val first = LocalDate.of(year, parts[0].toInt(), 1)
            val ordinal = parts[2].toInt()
            val weekday = DayOfWeek.of(parts[1].toInt())
            val day = if (ordinal > 0) first.with(TemporalAdjusters.dayOfWeekInMonth(ordinal, weekday))
                else first.with(TemporalAdjusters.lastInMonth(weekday)).minusWeeks((-ordinal - 1).toLong())
            addHoliday("moving-$index", day, parts[4], if (parts[3] == "P") HolidayKind.PROFESSIONAL else HolidayKind.MEMORIAL)
        }
        addHoliday("programmer", LocalDate.ofYearDay(year, 256), "День программиста", HolidayKind.PROFESSIONAL)
        if (year >= 2029) addHoliday("biotechnologist", LocalDate.of(year, 10, 18), "День биотехнолога", HolidayKind.PROFESSIONAL)
    }.sortedWith(compareBy<Holiday> { it.date }.thenBy { it.kind.ordinal }.thenBy { it.title })

    private fun date(year: Int, value: String): LocalDate = LocalDate.of(year, value.substring(0, 2).toInt(), value.substring(3, 5).toInt())

